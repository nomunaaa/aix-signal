/**
 * 공개 열람(public browsing) 스위치.
 *
 * 켜면 로그인하지 않은 방문자도 앱의 모든 화면을 "볼" 수 있다.
 * 끄면 기존처럼 로그인 벽(RequireAuth 등)이 화면을 가린다.
 *
 * ── 이 스위치가 바꾸는 것 / 바꾸지 않는 것 ──────────────────────────
 *
 * 바꾼다: 화면을 통째로 가리던 "열람 게이트"만.
 *   - RequireAuth (약 10개 라우트 레이아웃을 감싼다)
 *   - Alerts의 전체 화면 잠금
 *   - Profile / BillingDashboard 의 마운트 시 /auth 리다이렉트
 *   - app/(app)/layout.tsx 의 전화번호 인증 미완료 → /signup 리다이렉트
 *
 * 바꾸지 않는다: 무언가를 "실행"할 때의 로그인 확인.
 *   결제·구독 취소·회원 탈퇴·알림 설정 저장·스냅샷 저장 등은 그대로 로그인을
 *   요구한다. 이건 UI 가림막이 아니라 실제 동작의 전제 조건이라, 풀어 주면
 *   비로그인 사용자가 실패할 수밖에 없는 버튼을 누르게 된다.
 *
 * ── 알아둘 것 ────────────────────────────────────────────────────
 * 데이터는 Supabase RLS가 여전히 막는다. 따라서 비로그인 방문자에게는
 * 레이아웃과 빈 상태가 보이고, 개인 데이터는 보이지 않는다. 이 스위치는
 * 권한을 여는 게 아니라 화면을 여는 것이다.
 *
 * 기본값은 켜짐. 특정 환경에서만 닫으려면 NEXT_PUBLIC_PUBLIC_BROWSING=0.
 */
export const PUBLIC_BROWSING = process.env.NEXT_PUBLIC_PUBLIC_BROWSING !== '0';
